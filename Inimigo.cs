public class Inimigo
{
    // Atributos do inimigo
    public int vida;
    public float velocidade;
    public int atributoGenetico;

    // Construtor
    public Inimigo(int vida, float velocidade, int atributoGenetico)
    {
        this.vida = vida;
        this.velocidade = velocidade;
        this.atributoGenetico = atributoGenetico;
    }
}